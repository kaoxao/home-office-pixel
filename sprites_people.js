// ---- ตรวจรูปแบบตอนโหลด: ผิดตรงไหน throw ทันที ----
(function(){
  var errs = [];
  Object.keys(window.SPR_PEOPLE).forEach(function(n){
    var s = window.SPR_PEOPLE[n];
    if(s.anchor !== 'bottom-center') errs.push(n+': anchor');
    if(!s.frames || !s.frames.length) errs.push(n+': no frames');
    (s.frames||[]).forEach(function(fr, fi){
      if(fr.length !== s.h) errs.push(n+' frame '+fi+': rows '+fr.length+' != h '+s.h);
      fr.forEach(function(row, ri){
        if(row.length !== s.w) errs.push(n+' frame '+fi+' row '+ri+': len '+row.length+' != w '+s.w);
        for(var i=0;i<row.length;i++){ var ch=row[i]; if(ch!=='.' && !s.pal[ch]) errs.push(n+' frame '+fi+' row '+ri+': char "'+ch+'" not in pal'); }
      });
    });
  });
  if(errs.length) throw new Error('SPR_PEOPLE invalid:\n'+errs.join('\n'));
})();

